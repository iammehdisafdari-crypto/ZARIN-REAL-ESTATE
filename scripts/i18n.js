let activeLang = 'en';

export function getCurrentLanguage() {
  try {
    return localStorage.getItem('zarin_lang') || activeLang;
  } catch (e) {
    return activeLang;
  }
}

export function setLanguage(lang) {
  if (!translations[lang]) return;
  activeLang = lang;

  try {
    localStorage.setItem('zarin_lang', lang);
  } catch (e) {}

  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'fa' ? 'rtl' : 'ltr';

  const dict = translations[lang];

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) {
      if (typeof dict[key] === 'string' && dict[key].includes('<') && dict[key].includes('>')) {
        el.innerHTML = dict[key];
      } else {
        el.textContent = dict[key];
      }
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key] !== undefined) {
      el.setAttribute('placeholder', dict[key]);
    }
  });

  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (dict[key] !== undefined) {
      el.setAttribute('title', dict[key]);
    }
  });

  document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria-label');
    if (dict[key] !== undefined) {
      el.setAttribute('aria-label', dict[key]);
    }
  });

  // Update active state of language buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    const isMatch = btn.dataset.lang === lang;
    btn.classList.toggle('active', isMatch);
    btn.classList.toggle('is-active', isMatch);
    btn.setAttribute('aria-pressed', isMatch ? 'true' : 'false');
    if (btn.classList.contains('mobile-lang-btn')) {
      btn.classList.toggle('bg-gold-400', isMatch);
      btn.classList.toggle('text-ink-900', isMatch);
      btn.classList.toggle('border-gold-line', isMatch);
      btn.classList.toggle('border-white-line', !isMatch);
      btn.classList.toggle('text-ash', !isMatch);
    }
    if (btn.classList.contains('text-ash')) {
      btn.classList.toggle('text-ash', !isMatch);
    }
  });

  // Dispatch global event for other scripts/components
  if (typeof window !== 'undefined') {
    window.dispatchEvent(new CustomEvent('zarin:languageChange', { detail: { lang } }));
  }
}

export function initI18n() {
  const initialLang = getCurrentLanguage();

  document.querySelectorAll('.lang-btn').forEach(btn => {
    if (!btn.dataset.i18nBound) {
      btn.dataset.i18nBound = 'true';
      btn.addEventListener('click', (e) => {
        e.preventDefault();
        const targetLang = btn.dataset.lang;
        if (targetLang) {
          setLanguage(targetLang);
        }
      });
    }
  });

  setLanguage(initialLang);
}

// Global exposure
if (typeof window !== 'undefined') {
  window.ZARIN_TRANSLATIONS = translations;
  window.ZARIN_I18N = {
    translations,
    setLanguage,
    initI18n,
    getCurrentLanguage
  };
  window.setLanguage = setLanguage;

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initI18n);
  } else {
    initI18n();
  }
}
